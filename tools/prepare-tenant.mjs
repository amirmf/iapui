import { mkdir, readFile, rename, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { z } from 'zod'

const tenantSchema = z.string().regex(/^[a-z][a-z0-9-]*$/)
const brandSchema = z.object({
  assets: z.object({
    loginLogo: z.string().regex(/^\//),
    sidebarLogo: z.string().regex(/^\//),
    customerAppHeaderLogo: z.string().regex(/^\//),
  }),
  domain_url: z.object({
    admin: z.url(),
    app: z.url(),
  }),
  environment: z.object({
    development: z.object({ VITE_API_BASE_URL: z.url() }),
    production: z.object({ VITE_API_BASE_URL: z.url() }),
  }),
  identity: z.object({
    loginCompany: z.string().min(1),
    loginTitle: z.string().min(1),
  }),
  myIapNavigation: z.object({
    background: z.string().min(1),
    backgroundDark: z.string().min(1),
  }),
  metadata: z.object({
    translationKeys: z.object({
      description: z.string().min(1),
      metaTitle: z.string().min(1),
      title: z.string().min(1),
      twitterCard: z.string().min(1),
      twitterDescription: z.string().min(1),
      twitterTitle: z.string().min(1),
    }),
  }),
})

const applications = ['iap-app', 'iap-admin']

function getTenant(env) {
  const value = env.match(/^TENANT=(.+)$/m)?.[1]?.trim()
  return tenantSchema.parse(value)
}

function getTranslation(locale, key) {
  const value = key.split('.').reduce((current, segment) => {
    if (!current || typeof current !== 'object') {
      return undefined
    }

    return current[segment]
  }, locale)

  if (typeof value !== 'string' || value.length === 0) {
    throw new Error(`Translation key "${key}" must resolve to a string.`)
  }

  return value
}

export async function prepareTenant({ mode, root = process.cwd() }) {
  if (mode !== 'development' && mode !== 'production') {
    throw new Error(
      'Tenant preparation mode must be development or production.'
    )
  }

  const tenant = getTenant(await readFile(path.join(root, '.env'), 'utf8'))
  const tenantDirectory = path.join(root, 'tenants', tenant)
  const brand = brandSchema.parse(
    JSON.parse(await readFile(path.join(tenantDirectory, 'brand.json'), 'utf8'))
  )
  const locale = JSON.parse(
    await readFile(path.join(tenantDirectory, 'locales', 'fa.json'), 'utf8')
  )
  const { translationKeys } = brand.metadata
  const contents = [
    `# Generated by tools/prepare-tenant.mjs for tenant=${tenant} mode=${mode}. Do not edit.`,
    `VITE_API_BASE_URL=${JSON.stringify(brand.environment[mode].VITE_API_BASE_URL)}`,
    `VITE_IAP_APP_DOMAIN_URL=${JSON.stringify(brand.domain_url.app)}`,
    `VITE_IAP_ADMIN_DOMAIN_URL=${JSON.stringify(brand.domain_url.admin)}`,
    `VITE_LOGIN_LOGO=${JSON.stringify(brand.assets.loginLogo)}`,
    `VITE_SIDEBAR_LOGIN_LOGO=${JSON.stringify(brand.assets.sidebarLogo)}`,
    `VITE_CUSTOMER_APP_HEADER_LOGO=${JSON.stringify(brand.assets.customerAppHeaderLogo)}`,
    `VITE_LOGIN_TITLE=${JSON.stringify(brand.identity.loginTitle)}`,
    `VITE_MY_IAP_NAV_BACKGROUND=${JSON.stringify(brand.myIapNavigation.background)}`,
    `VITE_MY_IAP_NAV_BACKGROUND_DARK=${JSON.stringify(brand.myIapNavigation.backgroundDark)}`,
    `VITE_LOGIN_COMPANY=${JSON.stringify(brand.identity.loginCompany)}`,
    `VITE_META_TITLE=${JSON.stringify(getTranslation(locale, translationKeys.title))}`,
    `VITE_META_META_TITLE=${JSON.stringify(getTranslation(locale, translationKeys.metaTitle))}`,
    `VITE_META_DESCRIPTION=${JSON.stringify(getTranslation(locale, translationKeys.description))}`,
    `VITE_META_TWITTER_CARD=${JSON.stringify(getTranslation(locale, translationKeys.twitterCard))}`,
    `VITE_META_TWITTER_TITLE=${JSON.stringify(getTranslation(locale, translationKeys.twitterTitle))}`,
    `VITE_META_TWITTER_DESCRIPTION=${JSON.stringify(getTranslation(locale, translationKeys.twitterDescription))}`,
    '',
  ].join('\n')

  await Promise.all(
    applications.map(async (application) => {
      const output = path.join(root, 'apps', application, `.env.${mode}.local`)
      await mkdir(path.dirname(output), { recursive: true })
      const temporary = `${output}.${process.pid}.tmp`
      await writeFile(temporary, contents, 'utf8')
      await rename(temporary, output)
    })
  )
}

const mode = process.argv[2] === '--mode' ? process.argv[3] : undefined
if (mode) {
  prepareTenant({ mode }).catch((error) => {
    console.error(error.message)
    process.exitCode = 1
  })
}
